/* Offline TypeORM SQL generation for an additive feature when no local DB is running.
 * Baseline plan columns match the committed entity before this feature. No database
 * connection is made; PostgreSQL QueryRunner generates and reverses the DDL.
 * A live migration:generate and migration:run remain required for drift validation.
 */
const fs = require('fs');
const path = require('path');
require('ts-node').register({ project: path.join(__dirname, '../tsconfig.json'), transpileOnly: true });
require('reflect-metadata');
const { DataSource, Table, TableForeignKey } = require('typeorm');

async function main() {
  const output = path.join(__dirname, '../src/database/migrations/1791000200000-SubscriptionManagement.ts');
  if (fs.existsSync(output) && !process.argv.includes('--overwrite-unapplied')) throw new Error('Migration already exists. Never regenerate an applied migration. Use --overwrite-unapplied only during feature development.');
  const source = new DataSource({ type: 'postgres', database: 'purposemint', schema: 'public', entities: [path.join(__dirname, '../src/entities/*.entity.ts')], synchronize: false });
  console.log('Building entity metadata.');
  await source.buildMetadatas();
  console.log(`Loaded ${source.entityMetadatas.length} entities.`);
  const runner = source.createQueryRunner();
  runner.enableSqlMemory();
  const plan = Table.create(source.getMetadata('subscription_plans'), source.driver);
  const originalColumns = new Set(['key', 'name', 'tagline', 'price_monthly', 'badge', 'description', 'features', 'cta_label', 'sort_order']);
  const baseline = plan.clone();
  baseline.columns = baseline.columns.filter((column) => originalColumns.has(column.name));
  baseline.indices = []; baseline.checks = [];
  runner.loadedTables = [baseline];
  for (const column of plan.columns.filter((column) => !originalColumns.has(column.name))) { console.log(`Generating column ${column.name}.`); await runner.addColumn(baseline, column); }
  for (const check of plan.checks.slice()) await runner.createCheckConstraint(plan, check);
  for (const index of plan.indices.slice()) await runner.createIndex(plan, index);
  for (const name of ['user_subscriptions', 'subscription_history', 'subscription_billing_records']) {
    const metadata = source.getMetadata(name);
    const table = Table.create(metadata, source.driver);
    table.foreignKeys = metadata.foreignKeys.map(TableForeignKey.create);
    await runner.createTable(table);
  }
  const sql = runner.getMemorySql();
  const timestamp = 1791000200000;
  const statements = (queries) => queries.map((query) => `    await queryRunner.query(${JSON.stringify(query.query)});`).join('\n');
  const data = [
    `UPDATE subscription_plans SET entitlements = '{"pathways":false,"communityChallenges":true}'::jsonb WHERE key = 'growth'`,
    `UPDATE subscription_plans SET entitlements = '{"pathways":true,"communityChallenges":true}'::jsonb WHERE key = 'elevate'`,
    `UPDATE subscription_plans SET is_default = true WHERE key = 'free'`,
    `INSERT INTO user_subscriptions (user_id, plan_key, status, billing, payment_status, started_at, renewal_at, failed_payments, version)
      SELECT u.id, p.key, 'active', jsonb_build_object('planKey',p.key,'planName',p.name,'planVersion',p.version,'cycle','monthly','currency','USD','amountCents',round(p.price_monthly*100)::int,'regularAmountCents',round(p.price_monthly*100)::int,'promotionEndsAt',NULL), CASE WHEN p.price_monthly = 0 THEN 'not_required' ELSE 'pending' END, u.created_at, now() + interval '1 month', 0, 1
      FROM users u JOIN subscription_plans p ON p.key = u.tier::text WHERE u.user_type = 'customer' AND u.deleted_at IS NULL`,
    `INSERT INTO subscription_history (subscription_id, action, previous_plan_key, new_plan_key, new_billing, effective_at)
      SELECT id, 'legacy_imported', NULL, plan_key, billing, started_at FROM user_subscriptions`,
    `INSERT INTO audit_events (actor_type, action, entity_type, entity_id, outcome, metadata)
      SELECT 'system', 'admin.subscription_changed', 'subscription', id::text, 'success', jsonb_build_object('action','legacy_imported','newBilling',billing) FROM user_subscriptions`,
    `CREATE FUNCTION subscription_journal_immutable() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Subscription history and billing records are append-only'; END; $$`,
    `CREATE TRIGGER subscription_history_immutable BEFORE UPDATE OR DELETE ON subscription_history FOR EACH ROW EXECUTE FUNCTION subscription_journal_immutable()`,
    `CREATE TRIGGER subscription_billing_immutable BEFORE UPDATE OR DELETE ON subscription_billing_records FOR EACH ROW EXECUTE FUNCTION subscription_journal_immutable()`,
  ];
  const content = `// DDL generated by TypeORM's PostgreSQL QueryRunner in SQL-memory mode.\n// Seed conversion and append-only protections follow the generated additive DDL.\nimport type { MigrationInterface, QueryRunner } from 'typeorm';\n\nexport class SubscriptionManagement${timestamp} implements MigrationInterface {\n  name = 'SubscriptionManagement${timestamp}';\n  async up(queryRunner: QueryRunner): Promise<void> {\n${statements(sql.upQueries)}\n${statements(data.map((query) => ({query})))}\n  }\n  async down(queryRunner: QueryRunner): Promise<void> {\n${statements(sql.downQueries.slice().reverse())}\n    await queryRunner.query('DROP FUNCTION subscription_journal_immutable()');\n  }\n}\n`;
  fs.writeFileSync(output, content);
  console.log(`Generated ${sql.upQueries.length} additive DDL statements and ${data.length} data/protection statements: ${path.basename(output)}`);
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
